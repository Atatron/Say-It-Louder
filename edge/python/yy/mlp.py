"""A tiny two-layer network (9 -> 16 -> 4) trained with plain numpy.

Small enough to run on any ESP32 in a few microseconds with no ML runtime,
which keeps the firmware simple. Weights are exported as a C header that
edge/firmware/you_yourself_edge/yy_core.c reads.
"""
from __future__ import annotations

import numpy as np


class MLP:
    def __init__(self, n_in: int, n_hidden: int, n_out: int, seed: int = 0):
        rng = np.random.default_rng(seed)
        self.W1 = rng.normal(0, np.sqrt(2 / n_in), (n_in, n_hidden))
        self.b1 = np.zeros(n_hidden)
        self.W2 = rng.normal(0, np.sqrt(2 / n_hidden), (n_hidden, n_out))
        self.b2 = np.zeros(n_out)
        self.mu = np.zeros(n_in)
        self.sd = np.ones(n_in)

    def _norm(self, X):
        return (X - self.mu) / self.sd

    def proba(self, X):
        h = np.maximum(self._norm(np.atleast_2d(X)) @ self.W1 + self.b1, 0)
        z = h @ self.W2 + self.b2
        z -= z.max(axis=1, keepdims=True)
        e = np.exp(z)
        return e / e.sum(axis=1, keepdims=True)

    def fit(self, X, y, epochs=600, lr=0.01, l2=1e-4):
        self.mu = X.mean(axis=0)
        self.sd = X.std(axis=0) + 1e-6
        Xn = self._norm(X)
        Y = np.eye(self.W2.shape[1])[y]
        params = [self.W1, self.b1, self.W2, self.b2]
        m = [np.zeros_like(p) for p in params]
        v = [np.zeros_like(p) for p in params]
        for t in range(1, epochs + 1):
            h_pre = Xn @ self.W1 + self.b1
            h = np.maximum(h_pre, 0)
            z = h @ self.W2 + self.b2
            z -= z.max(axis=1, keepdims=True)
            p = np.exp(z)
            p /= p.sum(axis=1, keepdims=True)
            g = (p - Y) / len(X)
            gW2 = h.T @ g + l2 * self.W2
            gb2 = g.sum(axis=0)
            gh = (g @ self.W2.T) * (h_pre > 0)
            gW1 = Xn.T @ gh + l2 * self.W1
            gb1 = gh.sum(axis=0)
            for i, gr in enumerate([gW1, gb1, gW2, gb2]):
                m[i] = 0.9 * m[i] + 0.1 * gr
                v[i] = 0.999 * v[i] + 0.001 * gr * gr
                mh = m[i] / (1 - 0.9 ** t)
                vh = v[i] / (1 - 0.999 ** t)
                params[i] -= lr * mh / (np.sqrt(vh) + 1e-8)
        return self

    def to_c_header(self, classes, provenance: str) -> str:
        def arr(name, a):
            flat = ", ".join(f"{float(x):.8g}f" for x in np.ravel(a))
            return f"static const float {name}[{a.size}] = {{{flat}}};\n"

        n_in, n_h = self.W1.shape
        n_out = self.W2.shape[1]
        lines = [
            "/* Generated by edge/python/train_emg.py. Do not edit by hand. */\n",
            f"/* Training data: {provenance} */\n",
            "#pragma once\n",
            f"#define YY_MLP_IN {n_in}\n#define YY_MLP_HID {n_h}\n#define YY_MLP_OUT {n_out}\n",
            "/* Classes: " + ", ".join(f"{i}={c}" for i, c in enumerate(classes)) + " */\n",
            arr("YY_MU", self.mu), arr("YY_SD", self.sd),
            arr("YY_W1", self.W1), arr("YY_B1", self.b1),
            arr("YY_W2", self.W2), arr("YY_B2", self.b2),
        ]
        return "".join(lines)
